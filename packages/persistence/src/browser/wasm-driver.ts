import type { BindableValue, Sqlite3Static } from "@sqlite.org/sqlite-wasm";
import sqlite3InitModule from "@sqlite.org/sqlite-wasm";

import type { SqliteRawDatabase, SqliteStatement } from "../driver.js";

/**
 * Browser OPFS driver: the opfs-sahpool VFS of the official
 * @sqlite.org/sqlite-wasm. It can only be initialized inside a dedicated Web
 * Worker (a platform limitation of OPFS SyncAccessHandle); sahpool allows a
 * single connection per origin, so initializing in a second tab fails.
 * Multi-tab arbitration is handled by the kernel layer (Web Locks); the driver
 * does not retry.
 */
/**
 * OPFS names from before the product was renamed to Lapis. Every browser
 * library already lives under them, and a SAH pool cannot be renamed in place,
 * so they stay. They are never shown to the author (the download is named
 * lapis-<date>.sqlite).
 */
export const OPFS_DATABASE_FILE = "narralume.sqlite";
const OPFS_POOL_NAME = "narralume-pool";

export async function createOpfsSahpoolDriver(
  filename = OPFS_DATABASE_FILE,
): Promise<SqliteRawDatabase> {
  const sqlite3: Sqlite3Static = await sqlite3InitModule();
  const poolUtil = await sqlite3.installOpfsSAHPoolVfs({
    name: OPFS_POOL_NAME,
    initialCapacity: 12,
  });
  // The pool's DB/VFS must be used explicitly: a bare oo1.DB lands in the wasm
  // in-memory FS and is lost on reload. (At runtime normalizeArgs accepts
  // (filename, flags); the type declarations only list filename.)
  const DbCtor = poolUtil.OpfsSAHPoolDb as unknown as new (
    filename: string,
    flags: string,
  ) => InstanceType<Sqlite3Static["oo1"]["DB"]>;
  const db = new DbCtor(filename, "ct");
  // Official sahpool recommendation: a single connection with an exclusive
  // lock; WAL works and gives a small performance gain.
  db.exec(
    "PRAGMA locking_mode = EXCLUSIVE; PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000; PRAGMA synchronous = NORMAL;",
  );

  // The repository layer passes SQL values
  // (string/number/bigint/null/Uint8Array), bound positionally.
  const bindable = (params: unknown[]): BindableValue[] =>
    params as BindableValue[];

  function queryRows(
    sql: string,
    params: unknown[],
  ): Record<string, unknown>[] {
    return db.exec({
      sql,
      bind: bindable(params),
      rowMode: "object",
      returnValue: "resultRows",
    }) as Record<string, unknown>[];
  }

  return {
    prepare(sql: string): SqliteStatement {
      return {
        run(...params: unknown[]) {
          db.exec({ sql, bind: bindable(params) });
          // prepare() always binds a single statement, so changes() is that
          // statement's affected row count. lastInsertRowid has no consumers
          // (all ids are generated by the application), so it is always 0.
          return {
            changes: db.changes() as number,
            lastInsertRowid: 0,
          };
        },
        get(...params: unknown[]) {
          return queryRows(sql, params)[0];
        },
        all(...params: unknown[]) {
          return queryRows(sql, params);
        },
      };
    },
    exec(sql: string) {
      db.exec(sql);
    },
    close() {
      db.close();
    },
    // Download my library (D6): the pool exports the full bytes of the file
    // (including data after checkpoint). The pool's filename map is keyed by
    // the absolute path normalized by getPath (starting with /).
    exportBytes() {
      const path = filename.startsWith("/") ? filename : `/${filename}`;
      return Promise.resolve(poolUtil.exportFile(path));
    },
  };
}
